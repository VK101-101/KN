/** Rough ambiguity resolver: a few well-known names map to one canonical city. */
export function searchCities(query: string, limit = 12): City[] {
  const q = query.trim().toLowerCase();
  if (!q) return CITIES.slice(0, limit);
  const starts: City[] = [];
  const contains: City[] = [];
  for (const c of CITIES) {
    const hay = `${c.name} ${c.state} ${c.country}`.toLowerCase();
    if (c.name.toLowerCase().startsWith(q)) starts.push(c);
    else if (hay.includes(q)) contains.push(c);
    if (starts.length + contains.length >= limit * 4) break;
  }
  return [...starts, ...contains].slice(0, limit);
}

export function findCity(name: string): City | undefined {
  return CITIES.find((c) => c.name.toLowerCase() === name.trim().toLowerCase());
}
